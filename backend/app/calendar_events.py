def _lines(block):
    return [line.split("|") for line in block.strip().splitlines()]


FIXED_EVENTS = [(int(m), int(d), h == "1", t) for m, d, h, t in _lines(_FIXED)]
GREGORIAN_EVENTS = [(int(m), int(d), t) for m, d, t in _lines(_GREGORIAN)]
LUNAR_RULES = {int(i): (int(m), int(d), t) for i, m, d, t in _lines(_LUNAR_RULES)}


def _parse_lunar_years():
    parsed, flags = {}, {}
    for year, text in _LUNAR_YEARS.items():
        items = []
        for token in text.split():
            holiday = token.endswith("h")
            jm, jd, rule = token.rstrip("h").split(".")
            items.append((int(jm), int(jd), int(rule), holiday))
            flags.setdefault(int(rule), []).append(holiday)
        parsed[year] = items
    # rule -> is it normally a holiday (used for years without exact data)
    default_holiday = {rule: sum(v) * 2 > len(v) for rule, v in flags.items()}
    return parsed, default_holiday


LUNAR_BY_YEAR, LUNAR_DEFAULT_HOLIDAY = _parse_lunar_years()


def _jalali_year_start(year):
    return jdatetime.date(year, 1, 1).togregorian()


def _build_hijri_starts():
    starts = set()
    for year, indexes in _HIJRI_STARTS_BY_YEAR.items():
        base = _jalali_year_start(year)
        for index in indexes:
            starts.add(base + timedelta(days=index))
    return sorted(starts)


HIJRI_STARTS = _build_hijri_starts()
_HIJRI_FIRST_INDEX = _HIJRI_FIRST_MONTH[0] * 12 + (_HIJRI_FIRST_MONTH[1] - 1)


def _tabular_hijri(g):
    """Civil (tabular) Islamic calendar: always available, but only approximate."""
    jdn = g.toordinal() + 1721425
    l = jdn - 1948440 + 10632
    n = (l - 1) // 10631
    l = l - 10631 * n + 354
    j = ((10985 - l) // 5316) * ((50 * l) // 17719) + (l // 5670) * ((43 * l) // 15238)
    l = l - ((30 - j) // 15) * ((17719 * j) // 50) - (j // 16) * ((15238 * j) // 43) + 29
    m = (24 * l) // 709
    d = l - (709 * m) // 24
    y = 30 * n + j - 30
    return y, m, d


def hijri_date(g):
    """(year, month, day, exact) for a Gregorian date."""
    if HIJRI_STARTS and HIJRI_STARTS[0] <= g <= HIJRI_STARTS[-1] + timedelta(days=28):
        i = bisect_right(HIJRI_STARTS, g) - 1
        total = _HIJRI_FIRST_INDEX + i
        return total // 12, total % 12 + 1, (g - HIJRI_STARTS[i]).days + 1, True
    y, m, d = _tabular_hijri(g)
    return y, m, d, False


def _approximate_lunar_events(jalali_year):
    """Lunar occasions of a year without official data, from the tabular calendar."""
    start = _jalali_year_start(jalali_year)
    length = 366 if jdatetime.date(jalali_year, 1, 1).isleap() else 365
    by_date = {}
    for rule, (hm, hd, _title) in LUNAR_RULES.items():
        for offset in range(length):
            g = start + timedelta(days=offset)
            _y, m, d = _tabular_hijri(g)
            if m == hm and d == hd:
                by_date.setdefault(g, []).append(rule)
    return by_date


_approx_cache = {}


def _lunar_events_for(g, jalali):
    items = []
    if jalali.year in LUNAR_BY_YEAR:
        for jm, jd, rule, holiday in LUNAR_BY_YEAR[jalali.year]:
            if jm == jalali.month and jd == jalali.day:
                items.append({"title": LUNAR_RULES[rule][2], "holiday": holiday, "kind": "lunar", "approx": False})
    else:
        if jalali.year not in _approx_cache:
            _approx_cache[jalali.year] = _approximate_lunar_events(jalali.year)
        for rule in _approx_cache[jalali.year].get(g, []):
            items.append({
                "title": LUNAR_RULES[rule][2],
                "holiday": LUNAR_DEFAULT_HOLIDAY.get(rule, False),
                "kind": "lunar",
                "approx": True,
            })
    return items


def events_for_day(g):
    """All occasions of one Gregorian date: list of {title, holiday, kind, approx}."""
    jalali = jdatetime.date.fromgregorian(date=g)
    events = []
    for m, d, holiday, title in FIXED_EVENTS:
        if m == jalali.month and d == jalali.day:
            events.append({"title": title, "holiday": holiday, "kind": "jalali", "approx": False})
    events.extend(_lunar_events_for(g, jalali))
    for m, d, title in GREGORIAN_EVENTS:
        if m == g.month and d == g.day:
            events.append({"title": title, "holiday": False, "kind": "world", "approx": False})
    events.sort(key=lambda e: not e["holiday"])
    return events
